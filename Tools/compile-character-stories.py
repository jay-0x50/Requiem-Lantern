"""Validate the scenario source and export the shared game catalog and readable script."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "기획서/캐릭터스토리/character-stories.json"


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    stories = data["characters"]
    assert data["schemaVersion"] == 1
    assert [s["id"] for s in stories] == ["lian", "sera", "noa"]
    assert all(s["rarity"] == 5 and 6 <= len(s["scenes"]) <= 10 for s in stories)
    known_speakers = {"", "카이", "리안", "세라", "노아", "미나토", "하이델"}
    code = ["// Generated by Tools/compile-character-stories.py; edit the scenario JSON.",
            "using System;", "using System.Collections.Generic;",
            "namespace RequiemLantern.Core", "{",
            "    [Serializable] public sealed class CharacterStoryData", "    {",
            "        public string Id, Name, Title, Summary, RecommendedAfter, BossName, BossKind, BossFaction, MusicId;",
            "        public List<StoryLine> Lines;", "    }",
            "    public static class CharacterStoryCatalog", "    {",
            "        public static readonly List<CharacterStoryData> All = new List<CharacterStoryData>", "        {"]
    doc = ["# ★5 캐릭터 스토리 · 리안 / 세라 / 노아", "",
           "작성일: 2026-10-12 · 시나리오 초안 v0.2 · 인간 적과 과거 관계 확장", "",
           "사용자 확인에 따라 대상은 기존 ★5인 리안·세라·노아 3인이다. ★4 미나토·하이델의 독립편은 이번 범위에 포함하지 않는다.", "",
           "기존 설정집의 가족 상실, 고아원 아이들의 군체화, 노아의 교단 탈주를 바탕으로 인간 적과 군체가 함께 등장하도록 확장했다. 로웬·엘렌·이브와 새 조직, 과거 관계는 검토 가능한 창작 초안이다. 인간은 스스로 내린 폭력과 배제의 명령에 책임을 지며, 전투 후에도 인간으로 남는다. 태양 실험의 전모, 카이의 정체, 최후의 그림자 정체는 이 이야기에서 밝히지 않는다.", "",
           "인간 세력과 장별 복선: [인간 적대 세력과 관계 서사](05_인간_적대세력과_관계서사.md).", "",
           "게임의 기록실 → 캐릭터 이야기에서 아래 대본을 읽을 수 있다. 보스전 장면은 현재 대화와 서술로 제공한다. 아래의 보스 패턴과 페이즈 전환은 전용 전투 구현을 위한 설계이며, 기존 1-1 전투에 적용된 패턴이 아니다.", "",
           "대본 원본: `캐릭터스토리/character-stories.json`. 수정 뒤 `python Tools/compile-character-stories.py`를 실행하면 이 문서와 Unity·Preview 공용 C# 대본을 갱신한다.", "",
           "음악 제작: [Suno 엔딩 보스 BGM 프롬프트](04_Suno_엔딩보스_BGM_프롬프트.md). 가사와 노래 대본은 작성하지 않는다.", "",
           "| 캐릭터 | 이야기 | 권장 감상 순서 | 엔딩 보스 | 음악 방향 |", "|---|---|---|---|---|"]
    directions = {"lian": "절제된 실내악 → 따뜻한 관현악 결의", "sera": "뒤틀린 장난감 왈츠 → 격정적인 6/8 록", "noa": "차가운 금속 전자음 → 스스로 박자를 고르는 누아르 브레이크비트"}
    for s in stories:
        kind = "인간" if s["boss"]["kind"] == "human" else "군체"
        doc.append(f'| {s["name"]} | {s["title"]} | {s["recommendedAfter"]} | {s["boss"]["name"]} / {kind} | {directions[s["id"]]} |')
    line_count = 0
    ids = set()
    for s in stories:
        boss = s["boss"]
        assert boss["kind"] in {"human", "umbra"}
        cast = s.get("supportingCast", [])
        encounters = s.get("secondaryEncounters", [])
        allowed_speakers = known_speakers | {c["name"] for c in cast} | {e["name"] for e in encounters} | {boss["name"], "문 너머의 목소리"}
        code.extend(["            new CharacterStoryData", "            {"])
        for field, value in [("Id", s["id"]), ("Name", s["name"]), ("Title", s["title"]), ("Summary", s["summary"]),
                             ("RecommendedAfter", s["recommendedAfter"]), ("BossName", boss["name"]), ("BossKind", boss["kind"]), ("BossFaction", boss["faction"]), ("MusicId", boss["musicId"])]:
            code.append(f"                {field} = {literal(value)},")
        code.extend(["                Lines = new List<StoryLine>", "                {"])
        doc.extend(["", f'## {s["name"]} · {s["title"]}', "", s["summary"], "",
                    f'**카이에게 모인 이유:** {s["joinReason"]}', "", f'**과거:** {s["past"]}', "",
                    f'**증오와 미련:** {s["resentment"]}', "", f'**권장 공개:** {s["recommendedAfter"]}', "",
                    "### 과거의 관계와 적대", ""])
        for person in cast:
            doc.extend([f'**{person["name"]} / {person["faction"]}**: {person["relationship"]}', ""])
        for encounter in encounters:
            kind = "인간" if encounter["kind"] == "human" else "군체"
            doc.extend([f'**중간 보스 · {encounter["name"]} / {kind}**: {encounter["role"]}', ""])
        classification = "인간 / " + boss["faction"] if boss["kind"] == "human" else boss["umbra"] + " 계열 군체"
        doc.extend(["### 엔딩 보스와 음악 전환", "", f'**{boss["name"]} / {classification}** — {boss["meaning"]}', "",
                    f'- 1페이즈: {boss["phase1"]}', f'- 2페이즈: {boss["phase2"]}',
                    f'- 감정 전환점: {boss["turningPoint"]}', f'- 음악 키: `{boss["musicId"]}_phase1` → `_phase2` → `_afterglow`.', "",
                    "음악은 체력 감소만으로 바뀌지 않는다. 캐릭터의 결의 대사를 마친 뒤, 다음 전술 입력이 열리는 시점에 결전곡으로 전환한다. 플레이어가 대응할 수 없는 컷신에서 음악의 정점을 소진하지 않도록 한다.", "",
                    f'**빛의 대가:** {s["cost"]}', "", f'**이후의 변화:** {s["ending"]}', "",
                    "### 장면별 대본", ""])
        for i, scene in enumerate(s["scenes"], 1):
            assert scene["id"] not in ids
            ids.add(scene["id"])
            assert scene["background"] in {"keep", "black", "ruins"}
            assert scene["portrait"] == s["id"] and len(scene["lines"]) >= 8
            doc.extend([f'#### {i}. {scene["title"]}', "", f'장소: {scene["location"]}', ""])
            for line in scene["lines"]:
                assert len(line) in {2, 3} and line[1].strip()
                speaker, text = line[:2]
                assert speaker in allowed_speakers, speaker
                cue = line[2] if len(line) == 3 else ""
                assert not cue or cue in {boss["musicId"] + suffix for suffix in ["_phase1", "_phase2", "_afterglow"]}
                caption = f'{s["name"]} · {i}/{len(s["scenes"])} · {scene["title"]}'
                code.append(f'                    new StoryLine({literal(speaker)}, {literal(text)}, {literal(scene["background"])}, {literal(scene["portrait"])}, true) {{ Location = {literal(scene["location"])}, Caption = {literal(caption)}, MusicCue = {literal(cue)} }},')
                if cue:
                    doc.extend([f'음악 큐: `{cue}`', ""])
                doc.extend([f'**{speaker or "서술"}**: {text}', ""])
                line_count += 1
        code.extend(["                }", "            },"])
    code.extend(["        };", "        public static CharacterStoryData Get(string id)", "        {",
                 "            return All.Find(s => string.Equals(s.Id, id, StringComparison.OrdinalIgnoreCase));", "        }", "    }", "}", ""])
    (ROOT / "RequiemLantern/Assets/Scripts/Core/CharacterStoryCatalog.cs").write_text("\n".join(code), encoding="utf-8")
    (ROOT / "기획서/03_캐릭터스토리_리안_세라_노아.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(f"PASS: 3 stories, {len(ids)} scenes, {line_count} lines; shared catalog and script exported.")


if __name__ == "__main__":
    main()
